    // ==================== Helper Methods ====================

    private UUID createCategory(String name, String slug) throws Exception {
        mockMvc.perform(post("/api/admin/categories")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {
                                  "name": "%s",
                                  "slug": "%s"
                                }
                                """.formatted(name, slug)))
                .andExpect(status().isCreated());

        return categoryRepository.findAll().stream()
                .filter(c -> c.slug().equals(slug))
                .findFirst()
                .orElseThrow()
                .id();
    }

    private UUID createTag(String name, String slug) throws Exception {
        mockMvc.perform(post("/api/admin/tags")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {
                                  "name": "%s",
                                  "slug": "%s"
                                }
                                """.formatted(name, slug)))
                .andExpect(status().isCreated());

        return tagRepository.findAll().stream()
                .filter(t -> t.slug().equals(slug))
                .findFirst()
                .orElseThrow()
                .id();
    }
