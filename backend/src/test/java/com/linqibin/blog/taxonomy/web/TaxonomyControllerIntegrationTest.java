    @Test
    void createCategoryEndpointReturnsCreatedCategory() throws Exception {
        mockMvc.perform(post("/api/admin/categories")
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("""
                                {
                                  "name": "Spring Boot",
                                  "slug": "spring-boot",
                                  "description": "Spring Boot tutorials"
                                }
                                """)
                        .header(RequestIdUtils.REQUEST_ID_HEADER, "create-category-request-id"))
                .andExpect(status().isCreated())
                .andExpect(content().contentTypeCompatibleWith(MediaType.APPLICATION_JSON))
                .andExpect(header().string(RequestIdUtils.REQUEST_ID_HEADER, "create-category-request-id"))
                .andExpect(jsonPath("$.code").value("OK"))
                .andExpect(jsonPath("$.message").value("success"))
                .andExpect(jsonPath("$.requestId").value("create-category-request-id"))
                .andExpect(jsonPath("$.data.name").value("Spring Boot"))
                .andExpect(jsonPath("$.data.slug").value("spring-boot"))
                .andExpect(jsonPath("$.data.description").value("Spring Boot tutorials"));
    }

